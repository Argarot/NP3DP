import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { parseProjectText } from '../../src/print/project';

test('control specimen produces a portable project and checked complete print file', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Prepare print', exact: true }).click();
  await page.getByRole('button', { name: 'Load control cup', exact: true }).click();
  await expect(page.getByLabel('Recipe name')).toHaveValue('01 Control cup');
  await expect(page.getByRole('button', { name: 'Export print', exact: true })).toBeEnabled();
  await expect(page.getByLabel('Job readiness')).toContainText('Ready for export review');
  const projectEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Save project', exact: true }).click();
  const projectFile = await (await projectEvent).path();
  const project = parseProjectText(await readFile(projectFile!, 'utf8'));
  expect(project.setup.foundation.enabled).toBe(true);
  expect(project.setup.printer.firmware).toBe('5.1.2+13478');
  await page.getByRole('button', { name: 'Export print', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('Command audit passed');
  const codeEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download .gcode', exact: true }).click();
  const code = await readFile((await (await codeEvent).path())!, 'utf8');
  expect(code).toContain('M109 R170');
  expect(code).toContain('; thumbnail_QOI begin 220x124');
  expect(code).toContain('; thumbnail_QOI begin 200x240');
  expect(code).toContain('M400\nM73 P100 R0');
  expect(code).toContain('; STAGE foundation');
  expect(code).toContain('; STAGE wall');
  expect(code).toContain('\nM84\n');
  const reportEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download print report', exact: true }).click();
  const report = JSON.parse(await readFile((await (await reportEvent).path())!, 'utf8'));
  expect(report.gcodeSha256).toBe(createHash('sha256').update(code).digest('hex'));
  expect(report.observations.printed).toBe(false);
  await page.getByRole('button', { name: 'Close print export' }).click();
  await page.getByRole('button', { name: 'Load wave coupon', exact: true }).click();
  await page.getByLabel('Open recipe file').setInputFiles(projectFile!);
  await expect(page.getByLabel('Recipe name')).toHaveValue('01 Control cup');
  await page.getByRole('tab', { name: 'Foundation', exact: true }).click();
  await expect(page.getByLabel('Include foundation and finish')).toBeChecked();
  expect(errors).toEqual([]);
});

