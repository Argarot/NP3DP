test('profile changes are reviewed, applied atomically and undone with the project', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Prepare print', exact: true }).click();
  await page.getByRole('button', { name: 'Load control cup', exact: true }).click();
  await page.getByRole('tab', { name: 'Printer', exact: true }).click();
  const config = '# generated by PrusaSlicer 2.9.0\nprinter_model = MINIIS\nnozzle_diameter = 0.4\nfilament_diameter = 1.75\nextrusion_multiplier = 0.97\ntemperature = 220\nfirst_layer_temperature = 220\nbed_temperature = 60\nfirst_layer_bed_temperature = 60\nmax_volumetric_speed = 0\nfilament_max_volumetric_speed = 4\nstart_gcode = M302 S0\\nM112\ncompatible_printers_condition =\n';
  await page.getByLabel('Import PrusaSlicer configuration file').setInputFiles({ name: 'synthetic-mini.ini', mimeType: 'text/plain', buffer: Buffer.from(config) });
  await expect(page.getByLabel('Imported profile review')).toBeVisible();
  const temp = page.getByRole('spinbutton', { name: 'Body nozzle value', exact: true });
  await expect(temp).toHaveValue('210');
  await page.getByRole('button', { name: 'Apply imported settings', exact: true }).click();
  await expect(temp).toHaveValue('220');
  await expect(page.getByLabel('Printer variant')).toHaveValue('unknown');
  await page.getByRole('button', { name: 'Undo recipe change', exact: true }).click();
  await expect(temp).toHaveValue('210');
  await page.getByRole('button', { name: 'Redo recipe change', exact: true }).click();
  await expect(temp).toHaveValue('220');
  await page.getByRole('button', { name: 'Export print', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('Command audit passed');
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download .gcode', exact: true }).click();
  const code = await readFile((await (await downloadEvent).path())!, 'utf8');
  expect(code).toContain('M109 R220.000');
  expect(code).not.toContain('M302');
  expect(code).not.toContain('M112');
});

test('unsupported firmware blocks full export and correction restores it', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Prepare print', exact: true }).click();
  await page.getByRole('button', { name: 'Load control cup', exact: true }).click();
  await page.getByRole('tab', { name: 'Printer', exact: true }).click();
  await page.getByLabel('Installed firmware').fill('6.0.0');
  await page.getByLabel('Installed firmware').press('Enter');
  await page.getByRole('button', { name: 'Export print', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('Export needs attention');
  await expect(page.getByRole('button', { name: 'Download .gcode', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Close print export' }).click();
  await page.getByLabel('Installed firmware').fill('5.1.2+13478');
  await page.getByLabel('Installed firmware').press('Enter');
  await expect(page.getByLabel('Job readiness')).toContainText('Ready for export review');
  for (const size of [{ width: 1280, height: 800 }, { width: 390, height: 844 }]) {
    await page.setViewportSize(size);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  }
});
